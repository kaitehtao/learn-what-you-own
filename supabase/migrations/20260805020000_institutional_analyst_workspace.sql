-- Private institutional analyst workflow. These records never enter the public
-- D1 dossier store or public search unless a member separately submits research
-- through the moderated publication workflow.

create table if not exists public.analyst_workspaces (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  notebook_id bigint not null references public.research_notebooks(id) on delete cascade,
  ticker text not null,
  workflow_status text not null default 'triage',
  recommendation text not null default 'unrated',
  time_horizon text not null default 'long',
  conviction smallint not null default 1,
  consensus_view text not null default '',
  variant_view text not null default '',
  current_view text not null default '',
  next_catalyst text not null default '',
  next_catalyst_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint analyst_workspace_ticker_check check (ticker ~ '^[A-Z0-9.\-]{1,12}$'),
  constraint analyst_workspace_status_check check (workflow_status in ('triage','researching','ready_for_review','owned','rejected','archived')),
  constraint analyst_workspace_recommendation_check check (recommendation in ('unrated','positive','neutral','negative')),
  constraint analyst_workspace_horizon_check check (time_horizon in ('short','medium','long')),
  constraint analyst_workspace_conviction_check check (conviction between 1 and 5),
  constraint analyst_workspace_text_check check (length(consensus_view) <= 12000 and length(variant_view) <= 12000 and length(current_view) <= 20000),
  unique (user_id, ticker),
  unique (user_id, notebook_id)
);

create table if not exists public.analyst_thesis_drivers (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  direction text not null default 'neutral',
  rank smallint not null default 1,
  title text not null,
  hypothesis text not null default '',
  metric text not null default '',
  current_reading text not null default '',
  target_reading text not null default '',
  epic_effect boolean not null default false,
  epic_predictability boolean not null default false,
  epic_independence boolean not null default false,
  epic_consensus_gap boolean not null default false,
  importance smallint not null default 3,
  confidence smallint not null default 3,
  falsifier text not null default '',
  next_catalyst text not null default '',
  source_url text not null default '',
  evidence_date date,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint analyst_driver_direction_check check (direction in ('bull','bear','neutral')),
  constraint analyst_driver_rank_check check (rank between 1 and 10),
  constraint analyst_driver_score_check check (importance between 1 and 5 and confidence between 1 and 5),
  constraint analyst_driver_status_check check (status in ('active','confirmed','weakened','invalidated','archived')),
  constraint analyst_driver_title_check check (length(trim(title)) between 1 and 160),
  constraint analyst_driver_source_check check (length(source_url) <= 2000)
);

create table if not exists public.analyst_valuation_scenarios (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  scenario text not null,
  probability_pct numeric(5,2) not null default 0,
  price_target numeric(18,4),
  revenue_growth_pct numeric(8,3),
  margin_pct numeric(8,3),
  exit_multiple numeric(10,3),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint analyst_scenario_case_check check (scenario in ('bull','base','bear')),
  constraint analyst_scenario_probability_check check (probability_pct between 0 and 100),
  constraint analyst_scenario_price_check check (price_target is null or price_target >= 0),
  constraint analyst_scenario_notes_check check (length(notes) <= 12000),
  unique (workspace_id, scenario)
);

create table if not exists public.analyst_decision_journal (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  decision text not null,
  observed_price numeric(18,4),
  conviction smallint not null default 1,
  rationale text not null,
  key_risk text not null default '',
  next_catalyst text not null default '',
  created_at timestamptz not null default now(),
  constraint analyst_decision_type_check check (decision in ('watch','research','add','hold','reduce','exit','reject')),
  constraint analyst_decision_price_check check (observed_price is null or observed_price >= 0),
  constraint analyst_decision_conviction_check check (conviction between 1 and 5),
  constraint analyst_decision_rationale_check check (length(trim(rationale)) between 12 and 20000)
);

create index if not exists analyst_workspaces_user_updated_idx on public.analyst_workspaces (user_id, updated_at desc);
create index if not exists analyst_drivers_workspace_rank_idx on public.analyst_thesis_drivers (workspace_id, rank, updated_at desc);
create index if not exists analyst_scenarios_workspace_idx on public.analyst_valuation_scenarios (workspace_id, scenario);
create index if not exists analyst_decisions_workspace_created_idx on public.analyst_decision_journal (workspace_id, created_at desc);

drop trigger if exists analyst_workspaces_set_updated_at on public.analyst_workspaces;
create trigger analyst_workspaces_set_updated_at before update on public.analyst_workspaces for each row execute function public.set_updated_at();
drop trigger if exists analyst_drivers_set_updated_at on public.analyst_thesis_drivers;
create trigger analyst_drivers_set_updated_at before update on public.analyst_thesis_drivers for each row execute function public.set_updated_at();
drop trigger if exists analyst_scenarios_set_updated_at on public.analyst_valuation_scenarios;
create trigger analyst_scenarios_set_updated_at before update on public.analyst_valuation_scenarios for each row execute function public.set_updated_at();

alter table public.analyst_workspaces enable row level security;
alter table public.analyst_thesis_drivers enable row level security;
alter table public.analyst_valuation_scenarios enable row level security;
alter table public.analyst_decision_journal enable row level security;

drop policy if exists "Members own analyst workspaces" on public.analyst_workspaces;
create policy "Members own analyst workspaces" on public.analyst_workspaces for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Members own thesis drivers" on public.analyst_thesis_drivers;
create policy "Members own thesis drivers" on public.analyst_thesis_drivers for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Members own valuation scenarios" on public.analyst_valuation_scenarios;
create policy "Members own valuation scenarios" on public.analyst_valuation_scenarios for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Members own decision journals" on public.analyst_decision_journal;
create policy "Members own decision journals" on public.analyst_decision_journal for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

revoke all on public.analyst_workspaces, public.analyst_thesis_drivers, public.analyst_valuation_scenarios, public.analyst_decision_journal from anon;
grant select, insert, update, delete on public.analyst_workspaces, public.analyst_thesis_drivers, public.analyst_valuation_scenarios, public.analyst_decision_journal to authenticated;
grant usage, select on sequence public.analyst_workspaces_id_seq, public.analyst_thesis_drivers_id_seq, public.analyst_valuation_scenarios_id_seq, public.analyst_decision_journal_id_seq to authenticated;
