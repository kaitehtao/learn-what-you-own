-- User identity and private member records for Learn What You Own.
-- Run this migration in the Supabase SQL editor or with `supabase db push`.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text not null default '',
  role text not null default 'member' check (role in ('member', 'contributor', 'editor', 'admin')),
  onboarding_complete boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9_]{3,24}$')
);

create unique index if not exists profiles_username_lower_key on public.profiles (lower(username));

create table if not exists public.watchlist_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null check (ticker = upper(ticker) and length(ticker) between 1 and 12),
  created_at timestamptz not null default now(),
  unique (user_id, ticker)
);

create table if not exists public.portfolio_positions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null,
  account_label text not null default 'Primary portfolio',
  shares numeric,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contributions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null,
  contribution_type text not null,
  claim text not null,
  why_it_matters text not null,
  source_url text not null,
  evidence_date date not null,
  confidence text not null,
  time_horizon text not null,
  expertise text not null default '',
  position_disclosure text not null,
  conflict_disclosure text not null default '',
  status text not null default 'submitted' check (status in ('submitted', 'needs_revision', 'approved', 'rejected')),
  moderation_note text not null default '',
  moderated_by uuid references public.profiles(user_id),
  moderated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists contributions_ticker_status_idx on public.contributions (ticker, status, created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles for each row execute function public.set_updated_at();
drop trigger if exists portfolio_set_updated_at on public.portfolio_positions;
create trigger portfolio_set_updated_at before update on public.portfolio_positions for each row execute function public.set_updated_at();
drop trigger if exists contributions_set_updated_at on public.contributions;
create trigger contributions_set_updated_at before update on public.contributions for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  requested_username text := coalesce(new.raw_user_meta_data ->> 'username', '');
  generated_username text := 'user_' || substr(replace(new.id::text, '-', ''), 1, 12);
  chosen_username text;
  completed boolean;
begin
  completed := requested_username ~ '^[A-Za-z0-9_]{3,24}$'
    and not exists (select 1 from public.profiles where lower(username) = lower(requested_username));
  chosen_username := case when completed then requested_username else generated_username end;
  insert into public.profiles (user_id, username, display_name, onboarding_complete)
  values (
    new.id,
    chosen_username,
    coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), nullif(new.raw_user_meta_data ->> 'name', ''), chosen_username),
    completed
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

