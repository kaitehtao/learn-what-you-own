create or replace function public.update_own_profile(new_username text, new_display_name text default '')
returns public.profiles
language plpgsql
security definer set search_path = public
as $$
declare
  updated_profile public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if new_username !~ '^[A-Za-z0-9_]{3,24}$' then
    raise exception 'Invalid username';
  end if;
  update public.profiles
  set username = new_username,
      display_name = left(coalesce(nullif(trim(new_display_name), ''), new_username), 80),
      onboarding_complete = true
  where user_id = auth.uid()
  returning * into updated_profile;
  if updated_profile.user_id is null then
    raise exception 'Profile not found';
  end if;
  return updated_profile;
end;
$$;

revoke all on function public.update_own_profile(text, text) from public;
grant execute on function public.update_own_profile(text, text) to authenticated;
