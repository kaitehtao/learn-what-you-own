-- Private in-app notifications and opt-in message email delivery.

create table if not exists public.notification_preferences (
  user_id uuid primary key references public.profiles(user_id) on delete cascade,
  email_frequency text not null default 'off',
  email_message_preview boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint notification_preferences_frequency_check check (email_frequency in ('off', 'immediate', 'daily'))
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  actor_id uuid references public.profiles(user_id) on delete set null,
  kind text not null,
  title text not null,
  detail text not null default '',
  href text not null,
  entity_type text not null,
  entity_id bigint not null,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  constraint notifications_kind_check check (kind in ('private_message', 'public_message')),
  constraint notifications_title_check check (length(title) between 1 and 160),
  constraint notifications_detail_check check (length(detail) <= 240),
  constraint notifications_href_check check (href ~ '^/[A-Za-z0-9_?&=/%.-]+$'),
  unique (user_id, entity_type, entity_id)
);

create table if not exists public.email_notification_outbox (
  id bigint generated by default as identity primary key,
  notification_id bigint not null unique references public.notifications(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  frequency text not null,
  status text not null default 'queued',
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  sent_at timestamptz,
  last_error text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint email_outbox_frequency_check check (frequency in ('immediate', 'daily')),
  constraint email_outbox_status_check check (status in ('queued', 'sending', 'sent', 'failed', 'skipped'))
);

create index if not exists notifications_user_unread_idx
  on public.notifications (user_id, created_at desc) where read_at is null;
create index if not exists notifications_user_created_idx
  on public.notifications (user_id, created_at desc);
create index if not exists email_notification_outbox_due_idx
  on public.email_notification_outbox (status, frequency, next_attempt_at);

drop trigger if exists notification_preferences_set_updated_at on public.notification_preferences;
create trigger notification_preferences_set_updated_at before update on public.notification_preferences
for each row execute function public.set_updated_at();

drop trigger if exists email_notification_outbox_set_updated_at on public.email_notification_outbox;
create trigger email_notification_outbox_set_updated_at before update on public.email_notification_outbox
for each row execute function public.set_updated_at();

insert into public.notification_preferences (user_id)
select user_id from public.profiles
on conflict (user_id) do nothing;

-- Preserve unread state for messages that existed before the notification center.
insert into public.notifications (user_id, actor_id, kind, title, detail, href, entity_type, entity_id, read_at, created_at)
select
  message.recipient_id,
  message.sender_id,
  case when message.visibility = 'public' then 'public_message' else 'private_message' end,
  case when message.visibility = 'public' then 'New public message from @' else 'New private message from @' end || sender.username,
  message.subject,
  '/messages?open=' || message.id::text,
  'message',
  message.id,
  message.read_at,
  message.created_at
from public.private_messages as message
join public.profiles as sender on sender.user_id = message.sender_id
where message.recipient_deleted_at is null
on conflict (user_id, entity_type, entity_id) do nothing;

