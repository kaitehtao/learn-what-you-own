-- Private member-to-member messages. Emails never enter the messaging model;
-- usernames are resolved server-side to verified profile IDs.

create table if not exists public.private_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(user_id) on delete cascade,
  recipient_id uuid not null references public.profiles(user_id) on delete cascade,
  subject text not null,
  body text not null,
  read_at timestamptz,
  sender_deleted_at timestamptz,
  recipient_deleted_at timestamptz,
  created_at timestamptz not null default now(),
  constraint private_messages_not_to_self check (sender_id <> recipient_id),
  constraint private_messages_subject_length check (length(trim(subject)) between 1 and 120),
  constraint private_messages_body_length check (length(trim(body)) between 1 and 5000)
);

create index if not exists private_messages_recipient_inbox_idx
  on public.private_messages (recipient_id, created_at desc)
  where recipient_deleted_at is null;

create index if not exists private_messages_sender_sent_idx
  on public.private_messages (sender_id, created_at desc)
  where sender_deleted_at is null;

alter table public.private_messages enable row level security;

drop policy if exists "Participants read their private messages" on public.private_messages;
create policy "Participants read their private messages"
on public.private_messages for select
using (
  (auth.uid() = sender_id and sender_deleted_at is null)
  or (auth.uid() = recipient_id and recipient_deleted_at is null)
);

-- All writes pass through narrow security-definer functions. This prevents a
-- browser client from spoofing a sender, changing message text, or marking
-- another member's inbox as read.
revoke all on public.private_messages from anon, authenticated;
grant select on public.private_messages to authenticated;
grant usage, select on sequence public.private_messages_id_seq to authenticated;

create or replace function public.send_private_message(
  recipient_username text,
  message_subject text,
  message_body text
)
returns public.private_messages
language plpgsql
security definer set search_path = public
as $$
declare
  sender uuid := auth.uid();
  recipient uuid;
  created_message public.private_messages;
begin
  if sender is null then
    raise exception 'Authentication required';
  end if;
  if not exists (
    select 1 from public.profiles
    where user_id = sender and onboarding_complete = true
  ) then
    raise exception 'Complete your member profile before sending messages';
  end if;

  select user_id into recipient
  from public.profiles
  where lower(username) = lower(trim(recipient_username))
    and onboarding_complete = true
  limit 1;

  if recipient is null then
    raise exception 'Recipient username not found';
  end if;
  if recipient = sender then
    raise exception 'You cannot message yourself';
  end if;
  if length(trim(coalesce(message_subject, ''))) not between 1 and 120 then
    raise exception 'Subject must be between 1 and 120 characters';
  end if;
  if length(trim(coalesce(message_body, ''))) not between 1 and 5000 then
    raise exception 'Message must be between 1 and 5000 characters';
  end if;

  insert into public.private_messages (sender_id, recipient_id, subject, body)
  values (sender, recipient, trim(message_subject), trim(message_body))
  returning * into created_message;
  return created_message;
end;
$$;

create or replace function public.mark_private_message_read(message_id bigint)
returns public.private_messages
language plpgsql
security definer set search_path = public
as $$
declare
  updated_message public.private_messages;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  update public.private_messages
  set read_at = coalesce(read_at, now())
  where id = message_id
    and recipient_id = auth.uid()
    and recipient_deleted_at is null
  returning * into updated_message;
  if updated_message.id is null then
    raise exception 'Message not found';
  end if;
  return updated_message;
end;
$$;

create or replace function public.delete_private_message(message_id bigint)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  update public.private_messages
  set sender_deleted_at = case when sender_id = auth.uid() then now() else sender_deleted_at end,
      recipient_deleted_at = case when recipient_id = auth.uid() then now() else recipient_deleted_at end
  where id = message_id
    and (sender_id = auth.uid() or recipient_id = auth.uid());

  if not found then
    raise exception 'Message not found';
  end if;

  delete from public.private_messages
  where id = message_id
    and sender_deleted_at is not null
    and recipient_deleted_at is not null;
end;
$$;

revoke all on function public.send_private_message(text, text, text) from public;
revoke all on function public.mark_private_message_read(bigint) from public;
revoke all on function public.delete_private_message(bigint) from public;
grant execute on function public.send_private_message(text, text, text) to authenticated;
grant execute on function public.mark_private_message_read(bigint) to authenticated;
grant execute on function public.delete_private_message(bigint) to authenticated;
