-- Private, source-aware research notebooks. D1 remains the public dossier store.

create table if not exists public.research_notebooks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null,
  company_name text not null default '',
  thesis text not null default '',
  conviction text not null default 'watching',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_notebooks_ticker_check check (ticker ~ '^[A-Z0-9.\-]{1,12}$'),
  constraint research_notebooks_company_name_check check (length(company_name) <= 160),
  constraint research_notebooks_thesis_check check (length(thesis) <= 12000),
  constraint research_notebooks_conviction_check check (conviction in ('unranked', 'watching', 'low', 'medium', 'high')),
  unique (user_id, ticker)
);

create table if not exists public.research_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  notebook_id bigint references public.research_notebooks(id) on delete cascade,
  note_type text not null default 'general',
  title text not null,
  body text not null default '',
  status text not null default 'active',
  tags text[] not null default '{}',
  source_title text not null default '',
  source_url text not null default '',
  source_excerpt text not null default '',
  source_date date,
  pinned boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_notes_type_check check (note_type in ('general', 'source', 'thesis', 'bull_case', 'bear_case', 'risk', 'catalyst', 'question', 'task')),
  constraint research_notes_title_check check (length(trim(title)) between 1 and 160),
  constraint research_notes_body_check check (length(body) <= 30000),
  constraint research_notes_status_check check (status in ('active', 'done', 'archived')),
  constraint research_notes_source_title_check check (length(source_title) <= 240),
  constraint research_notes_source_url_check check (length(source_url) <= 2000),
  constraint research_notes_source_excerpt_check check (length(source_excerpt) <= 12000),
  constraint research_notes_tags_check check (cardinality(tags) <= 20)
);

create index if not exists research_notebooks_user_updated_idx
  on public.research_notebooks (user_id, updated_at desc);
create index if not exists research_notes_user_updated_idx
  on public.research_notes (user_id, updated_at desc);
create index if not exists research_notes_notebook_updated_idx
  on public.research_notes (notebook_id, updated_at desc);

drop trigger if exists research_notebooks_set_updated_at on public.research_notebooks;
create trigger research_notebooks_set_updated_at
before update on public.research_notebooks
for each row execute function public.set_updated_at();

drop trigger if exists research_notes_set_updated_at on public.research_notes;
create trigger research_notes_set_updated_at
before update on public.research_notes
for each row execute function public.set_updated_at();

alter table public.research_notebooks enable row level security;
alter table public.research_notes enable row level security;

drop policy if exists "Members read their own notebooks" on public.research_notebooks;
create policy "Members read their own notebooks"
on public.research_notebooks for select using (auth.uid() = user_id);

drop policy if exists "Members create their own notebooks" on public.research_notebooks;
create policy "Members create their own notebooks"
on public.research_notebooks for insert with check (auth.uid() = user_id);

drop policy if exists "Members update their own notebooks" on public.research_notebooks;
create policy "Members update their own notebooks"
on public.research_notebooks for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Members delete their own notebooks" on public.research_notebooks;
create policy "Members delete their own notebooks"
on public.research_notebooks for delete using (auth.uid() = user_id);

drop policy if exists "Members read their own research notes" on public.research_notes;
create policy "Members read their own research notes"
on public.research_notes for select using (auth.uid() = user_id);

drop policy if exists "Members create their own research notes" on public.research_notes;
create policy "Members create their own research notes"
on public.research_notes for insert with check (
  auth.uid() = user_id
  and (
    notebook_id is null
    or exists (
      select 1 from public.research_notebooks as owned_notebook
      where owned_notebook.id = research_notes.notebook_id and owned_notebook.user_id = auth.uid()
    )
  )
);

drop policy if exists "Members update their own research notes" on public.research_notes;
create policy "Members update their own research notes"
on public.research_notes for update using (auth.uid() = user_id) with check (
  auth.uid() = user_id
  and (
    notebook_id is null
    or exists (
      select 1 from public.research_notebooks as owned_notebook
      where owned_notebook.id = research_notes.notebook_id and owned_notebook.user_id = auth.uid()
    )
  )
);

drop policy if exists "Members delete their own research notes" on public.research_notes;
create policy "Members delete their own research notes"
on public.research_notes for delete using (auth.uid() = user_id);

revoke all on public.research_notebooks from anon;
revoke all on public.research_notes from anon;
grant select, insert, update, delete on public.research_notebooks to authenticated;
grant select, insert, update, delete on public.research_notes to authenticated;
grant usage, select on sequence public.research_notebooks_id_seq to authenticated;
grant usage, select on sequence public.research_notes_id_seq to authenticated;
