-- Research identity, moderated professional links, verified credentials, and
-- a public correction ledger for member profiles.

alter table public.profiles add column if not exists investment_style text not null default '';
alter table public.profiles add column if not exists time_horizon text not null default '';
alter table public.profiles add column if not exists expertise_areas text not null default '';
alter table public.profiles add column if not exists linkedin_url text;
alter table public.profiles add column if not exists website_url text;
alter table public.profiles add column if not exists links_status text not null default 'unreviewed';
alter table public.profiles add column if not exists credential_summary text not null default '';
alter table public.profiles add column if not exists credential_status text not null default 'unverified';
alter table public.profiles add column if not exists credential_verified_by uuid references public.profiles(user_id);
alter table public.profiles add column if not exists credential_verified_at timestamptz;

alter table public.profiles drop constraint if exists profiles_research_identity_length_check;
alter table public.profiles add constraint profiles_research_identity_length_check check (
  length(investment_style) <= 160
  and length(time_horizon) <= 80
  and length(expertise_areas) <= 240
  and length(credential_summary) <= 240
  and coalesce(length(linkedin_url), 0) <= 300
  and coalesce(length(website_url), 0) <= 300
);
alter table public.profiles drop constraint if exists profiles_links_status_check;
alter table public.profiles add constraint profiles_links_status_check check (links_status in ('unreviewed', 'pending', 'approved', 'rejected'));
alter table public.profiles drop constraint if exists profiles_credential_status_check;
alter table public.profiles add constraint profiles_credential_status_check check (credential_status in ('unverified', 'pending', 'verified', 'rejected'));

create table if not exists public.contribution_corrections (
  id bigint generated by default as identity primary key,
  contribution_id bigint references public.contributions(id) on delete set null,
  contributor_id uuid not null references public.profiles(user_id) on delete cascade,
  summary text not null check (length(trim(summary)) between 1 and 500),
  source_url text,
  recorded_by uuid not null references public.profiles(user_id),
  created_at timestamptz not null default now()
);

create index if not exists contribution_corrections_contributor_idx
  on public.contribution_corrections (contributor_id, created_at desc);

alter table public.contribution_corrections enable row level security;
drop policy if exists "Published correction history is public" on public.contribution_corrections;
create policy "Published correction history is public"
on public.contribution_corrections for select using (true);
grant select on public.contribution_corrections to anon, authenticated;

alter table public.admin_account_audit drop constraint if exists admin_account_audit_action_check;
alter table public.admin_account_audit add constraint admin_account_audit_action_check check (
  action in ('invite', 'role_update', 'delete', 'verification_resend', 'email_confirm', 'credential_verify', 'links_approve', 'links_reject')
);

