-- Authenticated members own their detailed earnings-model cells, assumptions,
-- evidence links, and revision history. Public pages receive only anonymized
-- aggregates through a server-side service-role query.

create table if not exists public.earnings_model_submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null,
  report_date date not null,
  fiscal_quarter text not null default '',
  thesis_case text not null default 'base',
  confidence smallint not null default 3,
  assumption_note text not null default '',
  source_url text not null default '',
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint earnings_model_submission_ticker_check check (ticker ~ '^[A-Z0-9.\-]{1,12}$'),
  constraint earnings_model_submission_case_check check (thesis_case in ('bull','base','bear')),
  constraint earnings_model_submission_confidence_check check (confidence between 1 and 5),
  constraint earnings_model_submission_note_check check (length(assumption_note) between 12 and 1500),
  constraint earnings_model_submission_source_check check (source_url = '' or (length(source_url) <= 2000 and source_url ~ '^https://')),
  unique (user_id, ticker, report_date)
);

create table if not exists public.earnings_model_cells (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null,
  report_date date not null,
  period_key text not null,
  metric_key text not null,
  value numeric not null,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint earnings_model_cell_ticker_check check (ticker ~ '^[A-Z0-9.\-]{1,12}$'),
  constraint earnings_model_cell_period_check check (period_key in ('report_quarter','next_quarter','current_fy','next_fy')),
  constraint earnings_model_cell_metric_check check (metric_key in ('revenue_millions','gross_profit_millions','operating_income_millions','adjusted_ebitda_millions','net_income_millions','diluted_shares_millions','adjusted_eps','operating_cash_flow_millions','capex_millions')),
  constraint earnings_model_cell_value_check check (abs(value) <= 10000000),
  unique (user_id, ticker, report_date, period_key, metric_key)
);

create table if not exists public.earnings_model_revisions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  ticker text not null,
  report_date date not null,
  period_key text not null,
  metric_key text not null,
  old_value numeric,
  new_value numeric,
  version integer not null,
  changed_at timestamptz not null default now(),
  constraint earnings_model_revision_ticker_check check (ticker ~ '^[A-Z0-9.\-]{1,12}$'),
  constraint earnings_model_revision_period_check check (period_key in ('report_quarter','next_quarter','current_fy','next_fy')),
  constraint earnings_model_revision_metric_check check (metric_key in ('revenue_millions','gross_profit_millions','operating_income_millions','adjusted_ebitda_millions','net_income_millions','diluted_shares_millions','adjusted_eps','operating_cash_flow_millions','capex_millions'))
);

create index if not exists earnings_model_submissions_public_idx on public.earnings_model_submissions (ticker, report_date, updated_at desc);
create index if not exists earnings_model_cells_aggregate_idx on public.earnings_model_cells (ticker, report_date, period_key, metric_key);
create index if not exists earnings_model_revisions_user_report_idx on public.earnings_model_revisions (user_id, ticker, report_date, changed_at desc);

drop trigger if exists earnings_model_submissions_set_updated_at on public.earnings_model_submissions;
create trigger earnings_model_submissions_set_updated_at before update on public.earnings_model_submissions for each row execute function public.set_updated_at();
drop trigger if exists earnings_model_cells_set_updated_at on public.earnings_model_cells;
create trigger earnings_model_cells_set_updated_at before update on public.earnings_model_cells for each row execute function public.set_updated_at();

alter table public.earnings_model_submissions enable row level security;
alter table public.earnings_model_cells enable row level security;
alter table public.earnings_model_revisions enable row level security;

drop policy if exists "Members own earnings model submissions" on public.earnings_model_submissions;
create policy "Members own earnings model submissions" on public.earnings_model_submissions for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Members own earnings model cells" on public.earnings_model_cells;
create policy "Members own earnings model cells" on public.earnings_model_cells for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Members read earnings model revisions" on public.earnings_model_revisions;
create policy "Members read earnings model revisions" on public.earnings_model_revisions for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Members append earnings model revisions" on public.earnings_model_revisions;
create policy "Members append earnings model revisions" on public.earnings_model_revisions for insert to authenticated with check ((select auth.uid()) = user_id);

revoke all on public.earnings_model_submissions, public.earnings_model_cells, public.earnings_model_revisions from anon;
grant select, insert, update, delete on public.earnings_model_submissions, public.earnings_model_cells to authenticated;
grant select, insert on public.earnings_model_revisions to authenticated;
grant usage, select on sequence public.earnings_model_submissions_id_seq, public.earnings_model_cells_id_seq, public.earnings_model_revisions_id_seq to authenticated;
