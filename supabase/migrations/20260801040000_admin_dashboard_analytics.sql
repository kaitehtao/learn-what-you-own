-- Administrator dashboard analytics and privileged account-action audit trail.
-- Anonymous visitor IDs are random browser UUIDs. IP addresses and user-agent
-- fingerprints are deliberately not stored.

create table if not exists public.site_visits (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  path text not null,
  referrer_host text not null default '',
  visit_bucket text not null,
  visited_at timestamptz not null default now(),
  constraint site_visits_path_check check (path ~ '^/[A-Za-z0-9_?&=/%.-]*$' and length(path) <= 240),
  constraint site_visits_referrer_check check (length(referrer_host) <= 180),
  constraint site_visits_bucket_check check (visit_bucket ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}$'),
  unique (visitor_id, path, visit_bucket)
);

create index if not exists site_visits_visited_at_idx on public.site_visits (visited_at desc);
create index if not exists site_visits_path_visited_at_idx on public.site_visits (path, visited_at desc);

create table if not exists public.admin_account_audit (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(user_id) on delete set null,
  target_user_id uuid,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint admin_account_audit_action_check check (action in ('invite', 'role_update', 'delete'))
);

create index if not exists admin_account_audit_created_idx on public.admin_account_audit (created_at desc);

alter table public.site_visits enable row level security;
alter table public.admin_account_audit enable row level security;

revoke all on public.site_visits from anon, authenticated;
revoke all on public.admin_account_audit from anon, authenticated;
revoke all on sequence public.site_visits_id_seq from anon, authenticated;
revoke all on sequence public.admin_account_audit_id_seq from anon, authenticated;

create or replace function public.admin_dashboard_visitor_metrics()
returns jsonb
language sql
security definer set search_path = public
as $$
  with daily as (
    select
      day::date as date,
      count(visit.id)::integer as page_views,
      count(distinct visit.visitor_id)::integer as visitors
    from generate_series(
      date_trunc('day', now()) - interval '13 days',
      date_trunc('day', now()),
      interval '1 day'
    ) as day
    left join public.site_visits visit
      on visit.visited_at >= day and visit.visited_at < day + interval '1 day'
    group by day
    order by day
  ), top_pages as (
    select path, count(*)::integer as page_views, count(distinct visitor_id)::integer as visitors
    from public.site_visits
    where visited_at >= now() - interval '7 days'
    group by path
    order by count(*) desc, path
    limit 8
  )
  select jsonb_build_object(
    'visitorsToday', (select count(distinct visitor_id) from public.site_visits where visited_at >= date_trunc('day', now())),
    'visitors7d', (select count(distinct visitor_id) from public.site_visits where visited_at >= now() - interval '7 days'),
    'pageViewsToday', (select count(*) from public.site_visits where visited_at >= date_trunc('day', now())),
    'pageViews7d', (select count(*) from public.site_visits where visited_at >= now() - interval '7 days'),
    'daily', coalesce((select jsonb_agg(jsonb_build_object('date', date, 'pageViews', page_views, 'visitors', visitors)) from daily), '[]'::jsonb),
    'topPages', coalesce((select jsonb_agg(jsonb_build_object('path', path, 'pageViews', page_views, 'visitors', visitors)) from top_pages), '[]'::jsonb)
  );
$$;

revoke all on function public.admin_dashboard_visitor_metrics() from public, anon, authenticated;
grant execute on function public.admin_dashboard_visitor_metrics() to service_role;
