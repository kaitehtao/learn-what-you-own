-- Private FACTS methodology workflow: Financial, Accounting, Credibility,
-- Timing, and Sector. Public evidence remains in D1; these records preserve an
-- individual member's judgment, action plan, channel checks, and postmortems.

alter table public.analyst_workspaces add column if not exists stock_profile text not null default 'unclassified';
alter table public.analyst_workspaces add column if not exists target_return_pct numeric(8,3);
alter table public.analyst_workspaces add column if not exists target_date date;
alter table public.analyst_workspaces add column if not exists entry_rule text not null default '';
alter table public.analyst_workspaces add column if not exists hold_rule text not null default '';
alter table public.analyst_workspaces add column if not exists exit_rule text not null default '';
alter table public.analyst_workspaces add column if not exists max_position_pct numeric(6,3);
alter table public.analyst_workspaces add column if not exists liquidity_plan text not null default '';

do $$ begin
  alter table public.analyst_workspaces add constraint analyst_workspace_stock_profile_check
    check (stock_profile in ('unclassified','growth','value','turnaround'));
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.analyst_workspaces add constraint analyst_workspace_target_return_check
    check (target_return_pct is null or target_return_pct between -100 and 10000);
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.analyst_workspaces add constraint analyst_workspace_position_size_check
    check (max_position_pct is null or max_position_pct between 0 and 100);
exception when duplicate_object then null; end $$;

create table if not exists public.analyst_facts_assessments (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  dimension text not null,
  status text not null default 'not_started',
  score smallint not null default 1,
  summary text not null default '',
  key_question text not null default '',
  evidence_gap text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint analyst_facts_dimension_check check (dimension in ('financial','accounting','credibility','timing','sector')),
  constraint analyst_facts_status_check check (status in ('not_started','in_progress','evidence_complete','reviewed')),
  constraint analyst_facts_score_check check (score between 1 and 5),
  constraint analyst_facts_text_check check (length(summary) <= 12000 and length(key_question) <= 4000 and length(evidence_gap) <= 4000),
  unique (workspace_id, dimension)
);

create table if not exists public.analyst_management_commitments (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  statement_date date not null,
  commitment text not null,
  expected_date date,
  actual_outcome text not null default '',
  status text not null default 'open',
  source_url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint analyst_commitment_status_check check (status in ('open','achieved','partially_achieved','delayed','missed','unverifiable')),
  constraint analyst_commitment_text_check check (length(trim(commitment)) between 8 and 8000 and length(actual_outcome) <= 8000 and length(source_url) <= 2000)
);

create table if not exists public.analyst_channel_checks (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  counterparty_type text not null,
  organization text not null default '',
  participant_role text not null default '',
  interaction_date date not null,
  finding text not null,
  thesis_impact text not null default 'neutral',
  confidence smallint not null default 3,
  source_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint analyst_channel_type_check check (counterparty_type in ('management','customer','supplier','distributor','competitor','consultant','trade_show','other')),
  constraint analyst_channel_impact_check check (thesis_impact in ('bull','bear','neutral')),
  constraint analyst_channel_confidence_check check (confidence between 1 and 5),
  constraint analyst_channel_finding_check check (length(trim(finding)) between 12 and 12000 and length(source_note) <= 4000)
);

create table if not exists public.analyst_postmortems (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.analyst_workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  outcome text not null,
  process_grade smallint not null default 3,
  thesis_result text not null default 'mixed',
  what_worked text not null default '',
  what_failed text not null default '',
  lesson text not null,
  created_at timestamptz not null default now(),
  constraint analyst_postmortem_outcome_check check (outcome in ('open','win','loss','avoided_loss','missed_opportunity')),
  constraint analyst_postmortem_result_check check (thesis_result in ('correct','incorrect','mixed','too_early','unresolved')),
  constraint analyst_postmortem_grade_check check (process_grade between 1 and 5),
  constraint analyst_postmortem_text_check check (length(trim(lesson)) between 12 and 12000 and length(what_worked) <= 12000 and length(what_failed) <= 12000)
);

create index if not exists analyst_facts_workspace_dimension_idx on public.analyst_facts_assessments (workspace_id, dimension);
create index if not exists analyst_commitments_workspace_date_idx on public.analyst_management_commitments (workspace_id, statement_date desc);
create index if not exists analyst_channel_checks_workspace_date_idx on public.analyst_channel_checks (workspace_id, interaction_date desc);
create index if not exists analyst_postmortems_workspace_created_idx on public.analyst_postmortems (workspace_id, created_at desc);

