-- Long-form research publishing. All reads and writes remain server-only so
-- application authorization is the single, auditable access boundary.

alter table public.notifications drop constraint if exists notifications_kind_check;
alter table public.notifications add constraint notifications_kind_check
  check (kind in ('private_message', 'public_message', 'research_publication', 'research_comment', 'moderation_update'));

create table if not exists public.research_publications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  author_username text not null,
  source_note_id bigint references public.research_notes(id) on delete set null,
  title text not null,
  summary text not null default '',
  body text not null default '',
  bull_case text not null default '',
  bear_case text not null default '',
  risks text not null default '',
  catalysts text not null default '',
  valuation text not null default '',
  tickers text[] not null default '{}',
  citations jsonb not null default '[]'::jsonb,
  position_disclosure text not null default '',
  conflict_disclosure text not null default '',
  visibility text not null default 'private',
  status text not null default 'draft',
  editorial_status text not null default 'not_submitted',
  revision_number integer not null default 1,
  published_at timestamptz,
  withdrawn_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_publications_title_check check (length(trim(title)) between 3 and 180),
  constraint research_publications_visibility_check check (visibility in ('private', 'followers', 'selected', 'public')),
  constraint research_publications_status_check check (status in ('draft', 'published', 'withdrawn')),
  constraint research_publications_editorial_check check (editorial_status in ('not_submitted', 'pending', 'approved', 'changes_requested', 'rejected')),
  constraint research_publications_citations_check check (jsonb_typeof(citations) = 'array')
);

create table if not exists public.research_publication_recipients (
  publication_id bigint not null references public.research_publications(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (publication_id, user_id)
);

create table if not exists public.research_publication_revisions (
  id bigint generated by default as identity primary key,
  publication_id bigint not null references public.research_publications(id) on delete cascade,
  revision_number integer not null,
  editor_user_id uuid not null references public.profiles(user_id) on delete cascade,
  snapshot jsonb not null,
  change_summary text not null default '',
  created_at timestamptz not null default now(),
  unique (publication_id, revision_number)
);

create table if not exists public.research_bookmarks (
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  publication_id bigint not null references public.research_publications(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, publication_id)
);

create table if not exists public.research_comments (
  id bigint generated by default as identity primary key,
  publication_id bigint not null references public.research_publications(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  author_username text not null,
  body text not null,
  status text not null default 'published',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_comments_body_check check (length(trim(body)) between 1 and 3000),
  constraint research_comments_status_check check (status in ('published', 'hidden', 'deleted'))
);

create index if not exists research_publications_feed_idx on public.research_publications (status, visibility, published_at desc);
create index if not exists research_publications_tickers_idx on public.research_publications using gin (tickers);
create index if not exists research_publications_author_idx on public.research_publications (lower(author_username), published_at desc);
create index if not exists research_comments_publication_idx on public.research_comments (publication_id, created_at);

drop trigger if exists research_publications_set_updated_at on public.research_publications;
create trigger research_publications_set_updated_at before update on public.research_publications
for each row execute function public.set_updated_at();
drop trigger if exists research_comments_set_updated_at on public.research_comments;
create trigger research_comments_set_updated_at before update on public.research_comments
for each row execute function public.set_updated_at();

alter table public.research_publications enable row level security;
alter table public.research_publication_recipients enable row level security;
alter table public.research_publication_revisions enable row level security;
alter table public.research_bookmarks enable row level security;
alter table public.research_comments enable row level security;

revoke all on public.research_publications, public.research_publication_recipients,
  public.research_publication_revisions, public.research_bookmarks, public.research_comments
  from public, anon, authenticated;
grant all on public.research_publications, public.research_publication_recipients,
  public.research_publication_revisions, public.research_bookmarks, public.research_comments to service_role;
grant usage, select on sequence public.research_publications_id_seq,
  public.research_publication_revisions_id_seq, public.research_comments_id_seq to service_role;

comment on table public.research_publications is
  'Server-authorized long-form research. Editorial approval does not automatically promote claims into the D1 dossier registry.';
