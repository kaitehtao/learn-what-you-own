-- Safety records are server-only. Existing message and follow functions are
-- intentionally unchanged; verified application routes enforce these records.

create table if not exists public.member_blocks (
  blocker_id uuid not null references public.profiles(user_id) on delete cascade,
  blocked_id uuid not null references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint member_blocks_not_self check (blocker_id <> blocked_id)
);
create table if not exists public.member_mutes (
  muter_id uuid not null references public.profiles(user_id) on delete cascade,
  muted_id uuid not null references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (muter_id, muted_id),
  constraint member_mutes_not_self check (muter_id <> muted_id)
);
create table if not exists public.community_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles(user_id) on delete cascade,
  entity_type text not null check (entity_type in ('member', 'publication', 'comment', 'message', 'contribution')),
  entity_id text not null,
  reason_code text not null check (reason_code in ('spam', 'harassment', 'misinformation', 'copyright', 'privacy', 'conflict', 'other')),
  details text not null default '',
  status text not null default 'open' check (status in ('open', 'reviewing', 'resolved', 'dismissed')),
  assigned_to uuid references public.profiles(user_id) on delete set null,
  resolution text not null default '',
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.moderation_actions (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(user_id) on delete set null,
  actor_username text not null,
  action text not null,
  reason_code text not null,
  entity_type text not null,
  entity_id text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.member_action_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  action_key text not null,
  created_at timestamptz not null default now()
);
create index if not exists community_reports_queue_idx on public.community_reports (status, created_at);
create index if not exists moderation_actions_entity_idx on public.moderation_actions (entity_type, entity_id, created_at desc);
create index if not exists member_action_events_rate_idx on public.member_action_events (user_id, action_key, created_at desc);
drop trigger if exists community_reports_set_updated_at on public.community_reports;
create trigger community_reports_set_updated_at before update on public.community_reports for each row execute function public.set_updated_at();

alter table public.member_blocks enable row level security;
alter table public.member_mutes enable row level security;
alter table public.community_reports enable row level security;
alter table public.moderation_actions enable row level security;
alter table public.member_action_events enable row level security;
revoke all on public.member_blocks, public.member_mutes, public.community_reports, public.moderation_actions, public.member_action_events from public, anon, authenticated;
grant all on public.member_blocks, public.member_mutes, public.community_reports, public.moderation_actions, public.member_action_events to service_role;
grant usage, select on sequence public.community_reports_id_seq, public.moderation_actions_id_seq, public.member_action_events_id_seq to service_role;
