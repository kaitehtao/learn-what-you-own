-- Allow a member account to be deleted without leaving privileged reviewer
-- references that block the auth.users -> profiles cascade. Historical
-- correction and moderation records remain, but the deleted reviewer becomes
-- anonymous rather than retaining a dangling personal identifier.

alter table public.contributions
  drop constraint if exists contributions_moderated_by_fkey;
alter table public.contributions
  add constraint contributions_moderated_by_fkey
  foreign key (moderated_by) references public.profiles(user_id) on delete set null;

alter table public.profiles
  drop constraint if exists profiles_credential_verified_by_fkey;
alter table public.profiles
  add constraint profiles_credential_verified_by_fkey
  foreign key (credential_verified_by) references public.profiles(user_id) on delete set null;

alter table public.contribution_corrections
  alter column recorded_by drop not null;
alter table public.contribution_corrections
  drop constraint if exists contribution_corrections_recorded_by_fkey;
alter table public.contribution_corrections
  add constraint contribution_corrections_recorded_by_fkey
  foreign key (recorded_by) references public.profiles(user_id) on delete set null;

create table if not exists public.account_deletion_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  status text not null default 'requested' check (status in ('requested', 'cancelled', 'completed', 'rejected')),
  requested_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles(user_id) on delete set null
);

create unique index if not exists account_deletion_requests_active_user_key
  on public.account_deletion_requests (user_id) where status = 'requested';
create index if not exists account_deletion_requests_status_requested_idx
  on public.account_deletion_requests (status, requested_at);

alter table public.account_deletion_requests enable row level security;
revoke all on public.account_deletion_requests from anon, authenticated;
