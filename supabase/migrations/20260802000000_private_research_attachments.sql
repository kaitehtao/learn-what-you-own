-- Private member-owned PDF attachments for company research notebooks.

create table if not exists public.research_attachments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  notebook_id bigint not null references public.research_notebooks(id) on delete cascade,
  file_name text not null,
  storage_path text not null unique,
  mime_type text not null default 'application/pdf',
  file_size bigint not null,
  created_at timestamptz not null default now(),
  constraint research_attachments_file_name_check check (length(trim(file_name)) between 1 and 240),
  constraint research_attachments_mime_type_check check (mime_type = 'application/pdf'),
  constraint research_attachments_file_size_check check (file_size between 1 and 20971520)
);

create index if not exists research_attachments_user_created_idx
  on public.research_attachments (user_id, created_at desc);
create index if not exists research_attachments_notebook_created_idx
  on public.research_attachments (notebook_id, created_at desc);

alter table public.research_attachments enable row level security;

drop policy if exists "Members read their own research attachments" on public.research_attachments;
create policy "Members read their own research attachments"
on public.research_attachments for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Members create their own research attachments" on public.research_attachments;
create policy "Members create their own research attachments"
on public.research_attachments for insert to authenticated
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.research_notebooks as owned_notebook
    where owned_notebook.id = research_attachments.notebook_id
      and owned_notebook.user_id = auth.uid()
  )
);

drop policy if exists "Members delete their own research attachments" on public.research_attachments;
create policy "Members delete their own research attachments"
on public.research_attachments for delete to authenticated
using (auth.uid() = user_id);

revoke all on public.research_attachments from anon;
grant select, insert, delete on public.research_attachments to authenticated;
grant usage, select on sequence public.research_attachments_id_seq to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('private-research-files', 'private-research-files', false, 20971520, array['application/pdf'])
on conflict (id) do update set
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Members upload private research PDFs" on storage.objects;
create policy "Members upload private research PDFs" on storage.objects for insert to authenticated
with check (
  bucket_id = 'private-research-files'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "Members read their private research PDFs" on storage.objects;
create policy "Members read their private research PDFs" on storage.objects for select to authenticated
using (
  bucket_id = 'private-research-files'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "Members remove their private research PDFs" on storage.objects;
create policy "Members remove their private research PDFs" on storage.objects for delete to authenticated
using (
  bucket_id = 'private-research-files'
  and (storage.foldername(name))[1] = auth.uid()::text
);
