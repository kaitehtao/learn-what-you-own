-- Private-company research profiles for member notebooks.
-- Public-company notebooks retain tickers; private companies deliberately do not
-- require or synthesize a ticker or exchange.

alter table public.research_notebooks
  alter column ticker drop not null;

alter table public.research_notebooks
  add column if not exists company_kind text not null default 'public',
  add column if not exists company_key text,
  add column if not exists website_url text not null default '',
  add column if not exists stage text not null default 'unknown',
  add column if not exists founded_year integer,
  add column if not exists headquarters text not null default '',
  add column if not exists sector text not null default '',
  add column if not exists business_model text not null default '',
  add column if not exists profile_summary text not null default '',
  add column if not exists currency text not null default 'USD',
  add column if not exists current_valuation numeric(24,2),
  add column if not exists valuation_as_of date,
  add column if not exists total_raised numeric(24,2),
  add column if not exists employee_count integer,
  add column if not exists last_verified_on date;

update public.research_notebooks
set company_key = lower(ticker)
where company_key is null and ticker is not null;

alter table public.research_notebooks
  alter column company_key set not null;

alter table public.research_notebooks
  drop constraint if exists research_notebooks_company_kind_check;
alter table public.research_notebooks
  add constraint research_notebooks_company_kind_check
  check (company_kind in ('public', 'private'));

alter table public.research_notebooks
  drop constraint if exists research_notebooks_identity_check;
alter table public.research_notebooks
  add constraint research_notebooks_identity_check check (
    (company_kind = 'public' and ticker is not null)
    or
    (company_kind = 'private' and ticker is null and length(trim(company_name)) between 1 and 160)
  );

alter table public.research_notebooks
  drop constraint if exists research_notebooks_company_key_check;
alter table public.research_notebooks
  add constraint research_notebooks_company_key_check
  check (company_key ~ '^[a-z0-9][a-z0-9-]{0,79}$');

alter table public.research_notebooks
  drop constraint if exists research_notebooks_venture_profile_check;
alter table public.research_notebooks
  add constraint research_notebooks_venture_profile_check check (
    length(website_url) <= 2000
    and length(stage) <= 80
    and (founded_year is null or founded_year between 1800 and 2200)
    and length(headquarters) <= 160
    and length(sector) <= 120
    and length(business_model) <= 5000
    and length(profile_summary) <= 12000
    and currency ~ '^[A-Z]{3}$'
    and (current_valuation is null or current_valuation >= 0)
    and (total_raised is null or total_raised >= 0)
    and (employee_count is null or employee_count >= 0)
  );

create unique index if not exists research_notebooks_user_company_key_idx
  on public.research_notebooks (user_id, company_kind, company_key);

create table if not exists public.private_company_metrics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  notebook_id bigint not null references public.research_notebooks(id) on delete cascade,
  metric_name text not null default 'ARR',
  period_label text not null,
  value numeric(24,4) not null,
  unit text not null default 'currency',
  currency text not null default 'USD',
  estimate_type text not null default 'actual',
  as_of_date date,
  notes text not null default '',
  source_title text not null default '',
  source_url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint private_company_metrics_name_check check (length(trim(metric_name)) between 1 and 80),
  constraint private_company_metrics_period_check check (length(trim(period_label)) between 1 and 40),
  constraint private_company_metrics_unit_check check (unit in ('currency', 'percent', 'count', 'multiple')),
  constraint private_company_metrics_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint private_company_metrics_estimate_check check (estimate_type in ('actual', 'company_forecast', 'investor_forecast')),
  constraint private_company_metrics_notes_check check (length(notes) <= 5000),
  constraint private_company_metrics_source_check check (length(source_title) <= 240 and length(source_url) <= 2000)
);

create table if not exists public.private_company_funding_rounds (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  notebook_id bigint not null references public.research_notebooks(id) on delete cascade,
  round_name text not null,
  stage text not null default 'other',
  close_date date,
  amount_raised numeric(24,2),
  pre_money_valuation numeric(24,2),
  post_money_valuation numeric(24,2),
  currency text not null default 'USD',
  security_type text not null default '',
  lead_investors text[] not null default '{}',
  participating_investors text[] not null default '{}',
  notes text not null default '',
  source_title text not null default '',
  source_url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint private_company_round_name_check check (length(trim(round_name)) between 1 and 120),
  constraint private_company_round_stage_check check (stage in ('pre_seed', 'seed', 'series_a', 'series_b', 'series_c', 'series_d_plus', 'growth', 'debt', 'secondary', 'other')),
  constraint private_company_round_values_check check (
    (amount_raised is null or amount_raised >= 0)
    and (pre_money_valuation is null or pre_money_valuation >= 0)
    and (post_money_valuation is null or post_money_valuation >= 0)
  ),
  constraint private_company_round_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint private_company_round_investors_check check (cardinality(lead_investors) <= 30 and cardinality(participating_investors) <= 100),
  constraint private_company_round_notes_check check (length(notes) <= 8000),
  constraint private_company_round_source_check check (length(source_title) <= 240 and length(source_url) <= 2000)
);

create table if not exists public.private_company_cap_table_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  notebook_id bigint not null references public.research_notebooks(id) on delete cascade,
  holder_name text not null,
  holder_type text not null default 'other',
  security_class text not null default '',
  shares numeric(24,4),
  ownership_percent numeric(9,6),
  fully_diluted_percent numeric(9,6),
  as_of_date date,
  notes text not null default '',
  source_title text not null default '',
  source_url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint private_company_cap_holder_check check (length(trim(holder_name)) between 1 and 200),
  constraint private_company_cap_type_check check (holder_type in ('founder', 'employee_pool', 'institutional', 'strategic', 'angel', 'other')),
  constraint private_company_cap_values_check check (
    (shares is null or shares >= 0)
    and (ownership_percent is null or ownership_percent between 0 and 100)
    and (fully_diluted_percent is null or fully_diluted_percent between 0 and 100)
  ),
  constraint private_company_cap_notes_check check (length(notes) <= 8000),
  constraint private_company_cap_source_check check (length(source_title) <= 240 and length(source_url) <= 2000)
);

create index if not exists private_company_metrics_notebook_idx
  on public.private_company_metrics (notebook_id, period_label);
create index if not exists private_company_metrics_owner_idx
  on public.private_company_metrics (user_id, notebook_id);
create index if not exists private_company_funding_notebook_idx
  on public.private_company_funding_rounds (notebook_id, close_date desc);
create index if not exists private_company_funding_owner_idx
  on public.private_company_funding_rounds (user_id, notebook_id);
create index if not exists private_company_cap_notebook_idx
  on public.private_company_cap_table_entries (notebook_id, as_of_date desc);
create index if not exists private_company_cap_owner_idx
  on public.private_company_cap_table_entries (user_id, notebook_id);

drop trigger if exists private_company_metrics_set_updated_at on public.private_company_metrics;
create trigger private_company_metrics_set_updated_at before update on public.private_company_metrics
for each row execute function public.set_updated_at();
drop trigger if exists private_company_funding_set_updated_at on public.private_company_funding_rounds;
create trigger private_company_funding_set_updated_at before update on public.private_company_funding_rounds
for each row execute function public.set_updated_at();
drop trigger if exists private_company_cap_set_updated_at on public.private_company_cap_table_entries;
create trigger private_company_cap_set_updated_at before update on public.private_company_cap_table_entries
for each row execute function public.set_updated_at();

alter table public.private_company_metrics enable row level security;
alter table public.private_company_funding_rounds enable row level security;
alter table public.private_company_cap_table_entries enable row level security;

do $$
declare table_name text;
begin
  foreach table_name in array array['private_company_metrics', 'private_company_funding_rounds', 'private_company_cap_table_entries']
  loop
    execute format('revoke all on public.%I from anon', table_name);
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
    execute format('drop policy if exists "Members read their own %s" on public.%I', table_name, table_name);
    execute format('create policy "Members read their own %s" on public.%I for select to authenticated using ((select auth.uid()) = user_id)', table_name, table_name);
    execute format('drop policy if exists "Members create their own %s" on public.%I', table_name, table_name);
    execute format('create policy "Members create their own %s" on public.%I for insert to authenticated with check ((select auth.uid()) = user_id and exists (select 1 from public.research_notebooks n where n.id = notebook_id and n.user_id = (select auth.uid()) and n.company_kind = ''private''))', table_name, table_name);
    execute format('drop policy if exists "Members update their own %s" on public.%I', table_name, table_name);
    execute format('create policy "Members update their own %s" on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id and exists (select 1 from public.research_notebooks n where n.id = notebook_id and n.user_id = (select auth.uid()) and n.company_kind = ''private''))', table_name, table_name);
    execute format('drop policy if exists "Members delete their own %s" on public.%I', table_name, table_name);
    execute format('create policy "Members delete their own %s" on public.%I for delete to authenticated using ((select auth.uid()) = user_id)', table_name, table_name);
  end loop;
end $$;

grant usage, select on sequence public.private_company_metrics_id_seq to authenticated;
grant usage, select on sequence public.private_company_funding_rounds_id_seq to authenticated;
grant usage, select on sequence public.private_company_cap_table_entries_id_seq to authenticated;

